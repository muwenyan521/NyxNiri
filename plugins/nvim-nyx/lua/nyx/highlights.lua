--- Paint the palette. `clear` resets first (a fresh colorscheme load);
--- refresh() repaints over whatever plugins have since defined.
function M.paint(p, clear)
  if clear then
    pcall(vim.cmd, "highlight clear")
    if vim.fn.exists("syntax_on") == 1 then
      pcall(vim.cmd, "syntax reset")
    end
    vim.g.colors_name = "nyx"
  end
  ui(p)
  syntax(p)
  treesitter(p)
  diagnostics(p)
  plugins(p)
end

function M.apply()
  local p = palette.get()
  M.paint(p, true)
  pcall(function() require("nyx.lualine").reload() end)
end

function M.refresh()
  local p = palette.get()
  M.paint(p, false)
  pcall(function() require("nyx.lualine").reload() end)
end

function M.palette()
  return palette.get()
end

return M
