local function diagnostics(p)
  local map = {
    Error = p.error,
    Warn = p.tertiary,
    Info = p.primary,
    Hint = p.outline,
    Ok = p.primary,
  }
  for name, colour in pairs(map) do
    set(0, "Diagnostic" .. name, { fg = colour })
    set(0, "DiagnosticUnderline" .. name, { undercurl = true, sp = colour })
    set(0, "DiagnosticVirtualText" .. name, { fg = colour, bg = p.surface })
    set(0, "DiagnosticFloating" .. name, { fg = colour, bg = p.surface })
    set(0, "DiagnosticSign" .. name, { fg = colour, bg = p.surface_dim })
  end
  set(0, "DiagnosticDeprecated", { fg = p.outline, strikethrough = true })
  set(0, "DiagnosticUnnecessary", { fg = p.faint, italic = true })

  set(0, "LspReferenceText", { bg = p.subtle })
  set(0, "LspReferenceRead", { bg = p.subtle })
  set(0, "LspReferenceWrite", { bg = p.subtle, underline = true })
  set(0, "LspSignatureActiveParameter", { bg = p.subtle, bold = true })
  set(0, "LspCodeLens", { fg = p.comment, italic = true })
  set(0, "LspCodeLensSeparator", { fg = p.faint })
  set(0, "LspInlayHint", { fg = p.comment, bg = p.raised, italic = true })
  set(0, "LspInfoBorder", { fg = p.border, bg = p.surface })

  local types = {
    ["@lsp.type.class"] = "@type",
    ["@lsp.type.decorator"] = "@attribute",
    ["@lsp.type.enum"] = "@type",
    ["@lsp.type.enumMember"] = "@constant",
    ["@lsp.type.function"] = "@function",
    ["@lsp.type.interface"] = "@type",
    ["@lsp.type.macro"] = "@function.macro",
    ["@lsp.type.method"] = "@function.method",
    ["@lsp.type.namespace"] = "@module",
    ["@lsp.type.parameter"] = "@variable.parameter",
    ["@lsp.type.property"] = "@property",
    ["@lsp.type.struct"] = "@type",
    ["@lsp.type.type"] = "@type",
    ["@lsp.type.typeParameter"] = "@type",
    ["@lsp.type.variable"] = "@variable",
    ["@lsp.mod.deprecated"] = "DiagnosticDeprecated",
  }
  for from, to in pairs(types) do
    link(from, to)
  end
end

